#!/usr/bin/env python3
r"""Run a compiled pytket circuit on Quantinuum's Selene emulator, via Guppy.

Why this file exists at all
---------------------------
Selene is the emulator Phase 1 of the SG Grand Challenge runs on, and it is the
only local tool that models the Helios *runtime* (and, uniquely, ion leakage and
seepage). It does not eat pytket circuits. Its documented inputs are HUGR — i.e.
Guppy — and QIR.

The QIR route was tried first and does not work with the versions installed
here: ``pytket.qir.pytket_to_qir`` emits ``__quantum__qis__read_result__body``,
and Selene's QIR validator (``qir-qis`` 0.1.10) rejects that symbol with
``Unsupported QIR QIS function``. That is true for every profile pytket-qir 2.0
offers (BASE, ADAPTIVE, PYTKET). So this module takes the other documented
route: it emits Guppy source for the circuit, in the Helios native gate set,
and lets Guppy compile it to HUGR.

The emission is a straight-line transliteration, which is exactly why it needs
checking rather than trusting: :func:`sampling_check` compares the emitted
program's sampled distribution against the exact statevector distribution of
the circuit it came from, and compares that discrepancy against the
shot-noise-only null obtained by sampling the exact distribution directly. A
transliteration bug shows up there; a correct one is indistinguishable from
shot noise.

Readout uses ``measure_leaked`` rather than ``measure`` throughout. It returns
a three-valued result (0, 1, leaked), so every shot separates two things that
prior art conflates:

* the **in-constraint probability** — did the surviving computational state
  still have Hamming weight k;
* the **physical leakage** — did an ion leave the computational manifold at
  all (Wood & Gambetta, PRA 97, 032306).

Conventions
-----------
Both pytket parameters and Guppy's ``angle`` are in **half-turns**, so the
parameters pass through unscaled. This is worth stating because it is the one
thing that was wrong first time and it fails silently: ``angle``'s docstring
notes that ``float(angle)`` converts to radians by multiplying by pi, which
reads like a radian constructor and is not one. The emission self-check below
caught it (TVD ratio 8.8 instead of ~1); nothing else would have.

Qubit ``q_j`` in the emitted program is the j-th qubit of the circuit in
pytket's own ordering, so the j-th ``"m"`` result is bit j of the big-endian
statevector index — the same convention as
:func:`quantum.dicke_xy.tket_statevector`.
"""

from __future__ import annotations

import importlib.util
import sys
import tempfile
import time
import uuid
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import numpy as np

from quantum.dicke_xy import HELIOS, HeliosSpec

